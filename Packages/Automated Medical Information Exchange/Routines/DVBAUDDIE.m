SUMOPT(DVBEVENT,DVBMAXHIST) ;
 N DIERR,DVBIENS,DVBERRMSG,DVBFDA,DVBFILE
 ; ZEXCEPT: DVBQUIT
 ;
 S DVBQUIT=0 ; Indicates a successful database update
 D SUMSTUB(DVBEVENT("DVBIEN19")) Q:DVBQUIT  ; DVBQUIT=1 if DVBEVENT is invalid
 ;
 ; Quit if no SUMMARY rec. "B: x-ref
 Q:'$D(^DVB(396.9991,"B",DVBEVENT("DVBIEN19"),DVBEVENT("DVBIEN19")))
 ; Quit, if no zeroith node in SUMMARY file for DVBIEN19
 Q:'$D(^DVB(396.9991,DVBEVENT("DVBIEN19"),0))
 ;
 I DVBEVENT("TASKEDI")=1 Q:'$$TASKDONE(DVBEVENT("DVBIENEVENT"))
 ;
 S DVBIENS=DVBEVENT("DVBIEN19")_",",DVBFILE=396.9991
 I $$GET1^DIQ(DVBFILE,DVBIENS,3,"E",,"DVBERRMSG")="" D  ;
 . S DVBFDA(DVBFILE,DVBIENS,3)=DVBEVENT("DTEVENTI")
 . D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMOPT^"_$T(+0))
 Q:DVBQUIT
 ;
 ; OP-LATEST AUDIT DATE/TIME
 S DVBFDA(DVBFILE,DVBIENS,4)=DVBEVENT("DTEVENTI") ; OP-LATEST AUDIT DATE/TIME
 S DVBFDA(DVBFILE,DVBIENS,5)=DVBEVENT("DVBIEN200") ;.. OP-LAST USED BY
 ;
 ; Increment the OP-USAGE COUNT field #6 & check for error
 S DVBFDA(DVBFILE,DVBIENS,6)=$$GET1^DIQ(DVBFILE,DVBIENS,6,"E",,"DVBERRMSG")+1
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMOPT^"_$T(+0)) Q:DVBQUIT
 ;
 I DVBEVENT("TASKED")="YES",DVBEVENT("DTENDEDI") D  ;
 . S DVBFDA(DVBFILE,DVBIENS,21)=DVBEVENT("DTEVENTI") ; from E-DATE/TIME
 . S DVBFDA(DVBFILE,DVBIENS,22)=DVBEVENT("DTENDEDI") ; from E-TASK END DATE/TIME
 . S DVBFDA(DVBFILE,DVBIENS,23)=DVBEVENT("DVBIEN200") ;.. from E-AUDITED USER
 ;
 D FILE^DIE("","DVBFDA","DVBERRMSG") ; Edit existing DVBIEN19 record
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMOPT^"_$T(+0)) Q:DVBQUIT
 ;
 ; Record the tasked DVBEVENT history in the OCCURANCE multiple
 D TASKHIST(.DVBEVENT,DVBMAXHIST)
 ;
 Q  ; QUIT SUMOPT
 ;
