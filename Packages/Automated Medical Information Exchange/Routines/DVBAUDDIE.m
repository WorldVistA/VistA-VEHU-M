SUMUSER(DVBEVENT) ; 
 ;
 S DVBQUIT=0 ; Indicates a successful database update
 ;
 I '$D(^DVB(396.9992,"B",DVBEVENT("DVBIEN200"),DVBEVENT("DVBIEN200"))) D  ;
 . N %DT,DVBDIALLVAL ; Left behind by UPDATE^DIE call during testing
 . N DIERR,DVBIENS,DVBERRMSG,DVBFDA,DVBFILE
 . S DVBIENS="+"_DVBEVENT("DVBIEN200")_",",DVBFILE=396.9992
 . S DVBFDA(DVBFILE,DVBIENS,.01)="`"_DVBEVENT("DVBIEN200")
 . D UPDATE^DIE("E","DVBFDA","","DVBERRMSG")
 . D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMUSER^"_$T(+0)) Q:DVBQUIT
 Q:DVBQUIT  ; Database server error occured on add to #396.9992
 ;
 N DVBFILE
 S DVBFILE=396.9992201
 I '$D(^DVB(396.9992,DVBEVENT("DVBIEN200"),"OPTION",DVBEVENT("DVBIEN19"),0)) D  Q
 . N %DT,DVBDIALLVAL ; Left behind by UPDATE^DIE call during testing
 . N DIERR,DVBIENS,DVBERRMSG,DVBFDA
 . S DVBIENS="+"_DVBEVENT("DVBIEN19")_","_DVBEVENT("DVBIEN200")_","
 . S DVBFDA(DVBFILE,DVBIENS,.01)="`"_DVBEVENT("DVBIEN19") ; OP-NAME
 . S DVBFDA(DVBFILE,DVBIENS,2)=DVBEVENT("DTEVENT") ;.. OP-FIRST USED DATE/TIME
 . S DVBFDA(DVBFILE,DVBIENS,3)=DVBEVENT("DTEVENT") ;.. OP-LAST USED DATE/TIME
 . S DVBFDA(DVBFILE,DVBIENS,4)=1 ; OP-USAGE COUNT (Set to 1)
 . ;
 . D UPDATE^DIE("E","DVBFDA","","DVBERRMSG")
 . D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMUSER^"_$T(+0)) Q:DVBQUIT
 ;
 N DVBCOUNTER,DIERR,DVBIENS,DVBERRMSG,DVBFDA
 ;
 S DVBIENS=DVBEVENT("DVBIEN19")_","_DVBEVENT("DVBIEN200")_","
 ;
 ; Update the OP-FIRST USED DATE/TIME sub-field #2
 I $$GET1^DIQ(DVBFILE,DVBIENS,2,"E",,"DVBERRMSG")="" D  ;
 . S DVBFDA(DVBFILE,DVBIENS,2)=DVBEVENT("DTEVENTI") ; OP-FIRST USED DATE/TIME
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMUSER^"_$T(+0)) Q:DVBQUIT
 ;
 S DVBFDA(DVBFILE,DVBIENS,3)=DVBEVENT("DTEVENTI") ;... OP-LAST USED DATE/TIME
 S DVBCOUNTER=$$GET1^DIQ(DVBFILE,DVBIENS,4,"E",,"DVBERRMSG") ; OP-USAGE COUNT
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMUSER^"_$T(+0)) Q:DVBQUIT
 S DVBCOUNTER=DVBCOUNTER+1 ;.................... Increment  OP-USAGE COUNT
 S DVBFDA(DVBFILE,DVBIENS,4)=DVBCOUNTER ;.... Update the OP-USAGE COUNT
 ;
 D FILE^DIE("","DVBFDA","DVBERRMSG") ; Update OPTION NAME (multiple)
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMUSER^"_$T(+0)) Q:DVBQUIT
 ;
 Q  ; Quit SUMUSER
