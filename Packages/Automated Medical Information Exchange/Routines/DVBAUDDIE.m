TASKHIST(DVBEVENT,DVBMAXHIST) ; 
 ;
 N %DT,DVBDIALLVAL ; Left behind by UPDATE^DIE call during testing
 N DIERR,DVBIENS,DVBLASTIEN,DVBNEWIEN,DVBNUMRECS
 N DVBERRMSG,DVBFDA,DVBFIELD,DVBFILE
 ; ZEXCEPT: DVBQUIT
 ;
 Q:'DVBEVENT("DTENDEDI")  ; Quit if no E-TASK END DATE/TIME defined
 ;
 S DVBFILE=396.9991
 S DVBLASTIEN=$P($G(^DVB(DVBFILE,DVBEVENT("DVBIEN19"),"OCCUR",0)),U,3) ; Last IEN
 S DVBNEWIEN=DVBLASTIEN+1
 ;
 S DVBNUMRECS=$P($G(^DVB(DVBFILE,DVBEVENT("DVBIEN19"),"OCCUR",0)),U,4)
 I DVBNUMRECS=DVBMAXHIST!(DVBNUMRECS>DVBMAXHIST) D  ;
 . F  D  Q:DVBNUMRECS=(DVBMAXHIST-1)!(DVBNUMRECS=0)
 . . N DVBIEN1ST
 . . S DVBIEN1ST=$O(^DVB(DVBFILE,DVBEVENT("DVBIEN19"),"OCCUR",0)) ; 1st OCCURENCE IEN
 . . I $D(^DVB(DVBFILE,DVBEVENT("DVBIEN19"),"OCCUR",DVBIEN1ST,0)) D  ;
 . . . D OCCURENC^DVBAUDDIK(DVBEVENT("DVBIEN19"),DVBIEN1ST) ; Delete 1st occur.
 . . S DVBNUMRECS=$P($G(^DVB(DVBFILE,DVBEVENT("DVBIEN19"),"OCCUR",0)),U,4)
 ;
 S DVBIENS="+1,"_DVBEVENT("DVBIEN19")_","
 S DVBFILE=396.9991201
 S DVBFDA(DVBFILE,DVBIENS,.01)=DVBNEWIEN ; DINUM multp. occurance number
 S DVBFDA(DVBFILE,DVBIENS,2)=DVBEVENT("DTEVENT") ;....E-DATE/TIME (started)
 S DVBFDA(DVBFILE,DVBIENS,3)=DVBEVENT("DTENDED") ;....E-TASK END DATE/TIME
 S DVBFDA(DVBFILE,DVBIENS,4)="`"_DVBEVENT("DVBIEN200") ; E-AUDITED USER
 ;
 D UPDATE^DIE("E","DVBFDA","","DVBERRMSG")
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","TASKHIST^"_$T(+0)) Q:DVBQUIT
 ;
 Q  ; Quit TASKHIST
