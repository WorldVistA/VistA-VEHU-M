AUDEVENT(DVBIEN19,DVBIEN200) ; Create a AMIE OPTION AUDIT DVBEVENT file #396.999 entry.
 ;                   'D AUDIT^DVBAUDOA'
 ;   AUDIT^DVBAUDOA
 ;
 N %DT,DVBDIALLVAL ; Left behind by UPDATE^DIE call during testing
 N DIERR,DVBIENS,DVBOPTNAME,DVBERRMSG,DVBFDA,DVBFILE,DVBUSERNAME
 ; ZEXCEPT: DVBQUIT,ZTSK
 ;
 S DVBQUIT=0 ; Indicates a successful database update
 ;
 S DVBIENS=+$G(DVBIEN19)_",",DVBFILE=19
 S DVBOPTNAME=$$GET1^DIQ(DVBFILE,DVBIENS,.01,"E",,"DVBERRMSG")
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","AUDEVENT^"_$T(+0)) Q:DVBQUIT
 I DVBOPTNAME']"" S DVBQUIT=1 Q
 ;
 S DVBIENS=+$G(DVBIEN200)_",",DVBFILE=200
 S DVBUSERNAME=$$GET1^DIQ(DVBFILE,DVBIENS,.01,"E",,"DVBERRMSG")
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","AUDEVENT^"_$T(+0)) Q:DVBQUIT
 I DVBUSERNAME']"" S DVBQUIT=1 Q
 ;I $P($$ACTIVE^XUSER(+$G(DVBIEN200)),U,2)'="ACTIVE" S DVBQUIT=1 Q
 S DVBFILE=19
 I $$GET1^DIQ(DVBFILE,DVBIEN19,20,"E",,"DVBERRMSG")'["D AUDIT^DVBAUDOA" S DVBQUIT=1 Q
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","AUDEVENT^"_$T(+0)) Q:DVBQUIT
 ;
 K DVBFDA ; Refresh FM data array (FDA)
 ;
 S DVBIENS="+1,",DVBFILE=396.999
 S DVBFDA(DVBFILE,DVBIENS,.01)=$$NOW^XLFDT() ; E-DATE/TIME [RD]
 S DVBFDA(DVBFILE,DVBIENS,2)="`"_DVBIEN19 ;...... E-OPTION ACCESSED [RP19']
 S DVBFDA(DVBFILE,DVBIENS,3)="`"_DVBIEN200 ;..... E-AUDITED USER    [RP200']
 I $G(ZTSK) D  ; If the audited DVBEVENT was a tasked job
 . N DVBIENOSF ; DVBIENOSF=IEN of the OPTION SCHEDULING file #19.2
 . N DVBOPTSCH ; Array of Option Scheduling attributes
 . S DVBIENOSF=$$FIND1^DIC(19.2,"","BO",DVBOPTNAME) Q:DVBIENOSF'>0
 . D OPTSCH^DVBAUDDIQ(DVBIENOSF) ; Get file #19.2 data, put DVBOPTSCH(array)
 . Q:DVBQUIT  ; Database server error detected.
 . Q:'$$OPTSCHOK^DVBAUDU1($T(+0),.DVBOPTSCH)  ; Option must be screened
 . S DVBFDA(DVBFILE,DVBIENS,4)="YES" ;........ E-TASKED AUDIT? [S] (1:YES)
 . S DVBFDA(DVBFILE,DVBIENS,5)=$JOB ; ........ E-TASKED JOB NUMBER [N]
 ;
 D UPDATE^DIE("E","DVBFDA","","DVBERRMSG") ; Add an DVBEVENT file record
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","AUDEVENT^"_$T(+0)) Q:DVBQUIT
 ;
 Q  ; Quit AUDEVENT
 ;
