 Q:$D(^DVB(DVBFILE,"B",DVBIEN19,DVBIEN19))  ;Record already exists, not needed
 ;
 I $L($G(DT))'=7 S DVBQUIT=1 Q  ; System var. DT is not defined or null
 S DVBOPTNAME=$$GET1^DIQ(19,DVBIEN19,.01,"E",,"DVBERRMSG")
 D DIERR^DVBAUDDILG1(60,5,"DVBERRMSG","SUMSTUB^"_$T(+0)) Q:DVBQUIT
 Q:DVBOPTNAME=""
