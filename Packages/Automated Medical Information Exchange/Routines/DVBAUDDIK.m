DELEVENT(DVBIENEVENT) ; Deletes an entry in the AMIE OPTION AUDIT
 ;   EVENT file #369.999
 N @($$DIK^DVBAUDNEW1())
 ; ZEXCEPT: DA,DIK,DVBQUIT
 ;
 S DVBQUIT=0 I '$G(DVBIENEVENT) S DVBQUIT=1 Q
 ;
 S DIK="^DVB(396.999,"
 S DA=DVBIENEVENT
 D ^DIK
 ;
 Q  ; Quit DELEVENT
