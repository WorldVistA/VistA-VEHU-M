DISPGRIDS() ;
 ;
 N CLINICIEN,CLINICNAME,COUNT,ENDDATE,GRIDDATE,HOLSCHED,PATTERN,STARTDATE,TNODE
 ;
 K ^XTMP("SDES949P-3")
 S COUNT=1
 S ^XTMP("SDES949P-3",COUNT)="*****************************POTENTIAL DISAPPEARING GRIDS REPORT*****************************"
 S COUNT=COUNT+1
 S ^XTMP("SDES949P-3",COUNT)="CLINIC IEN^CLINIC NAME^DESCRIPTION OF ISSUE//LIST OF APPTS ON SEPARATE ROWS"
 ;
 S CLINICIEN=0
 F  S CLINICIEN=$O(^SC(CLINICIEN)) Q:'CLINICIEN  D
 . Q:$$INACTIVE^SDESUTIL(CLINICIEN)
 . Q:$$GET1^DIQ(44,CLINICIEN,2,"I")'="C"
 . ;
 . S CLINICNAME=$$GET1^DIQ(44,CLINICIEN,.01)
 . S HOLSCHED=$S($$GET1^DIQ(44,CLINICIEN,1918.5,"I")="Y":1,1:0)
 . ;
 . F TNODE=0:1:6 I $D(^SC(CLINICIEN,"T"_TNODE)) D
 . . S STARTDATE=$$FMADD^XLFDT(DT,+1)
 . . S STARTDATE=$O(^SC(CLINICIEN,"T"_TNODE,STARTDATE),-1)
 . . I STARTDATE=0 S STARTDATE=$O(^SC(CLINICIEN,"T"_TNODE,STARTDATE))
 . . Q:'STARTDATE
 . . S ENDDATE=$O(^SC(CLINICIEN,"T"_TNODE,STARTDATE))
 . . I ENDDATE="" S ENDDATE=STARTDATE
 . . S PATTERN=^SC(CLINICIEN,"T"_TNODE,ENDDATE,1)
 . . I PATTERN="" D CHECKGRID(CLINICIEN,STARTDATE,ENDDATE,HOLSCHED,TNODE)
 . . F  S STARTDATE=$O(^SC(CLINICIEN,"T"_TNODE,STARTDATE)) Q:'STARTDATE!(ENDDATE=9999999)  D
 . . . S ENDDATE=$O(^SC(CLINICIEN,"T"_TNODE,STARTDATE))
 . . . I ENDDATE="" S ENDDATE=STARTDATE
 . . . S PATTERN=^SC(CLINICIEN,"T"_TNODE,ENDDATE,1)
 . . . I PATTERN="" D CHECKGRID(CLINICIEN,STARTDATE,ENDDATE,HOLSCHED,TNODE)
 Q
 ;
CHECKGRID(CLINICIEN,GRIDDATE,ENDDATE,HOLSCHED,TNODE) ;
 N FOUND
 S FOUND=0
 I GRIDDATE=9999999 S GRIDDATE=DT
 I GRIDDATE<DT S GRIDDATE=DT
 S GRIDDATE=GRIDDATE-.0001
 F  S GRIDDATE=$O(^SC(CLINICIEN,"ST",GRIDDATE)) Q:'GRIDDATE!(GRIDDATE>ENDDATE)  D
 . Q:($$FMTH^XLFDT(GRIDDATE)+4#7)'=TNODE
 . Q:($D(^HOLIDAY(GRIDDATE))&('HOLSCHED))
 . Q:$G(^SC(CLINICIEN,"ST",GRIDDATE,1))'["["
 . Q:$G(^SC(CLINICIEN,"OST",GRIDDATE,1))["["
 . ;
 . I 'FOUND D
 . . S COUNT=COUNT+1,FOUND=1
 . . S ^XTMP("SDES949P-3",COUNT)=CLINICIEN_U_CLINICNAME_U_"The T"_TNODE_" node pattern from "_$$FMTE^XLFDT(STARTDATE,5)_" to "_$$FMTE^XLFDT(ENDDATE,5)
 . . S ^XTMP("SDES949P-3",COUNT)=^XTMP("SDES949P-3",COUNT)_" has been removed, but there is ST node availability starting on "_$$FMTE^XLFDT(GRIDDATE,5)
 . ;
 . N APPTDTTM,APPTIEN,HASAPPTS
 . S APPTDTTM=GRIDDATE-.0001,HASAPPTS=0
 . F  S APPTDTTM=$O(^SC(CLINICIEN,"S",APPTDTTM)) Q:HASAPPTS!('APPTDTTM)!($P(APPTDTTM,".")>GRIDDATE)  D
 . . S APPTIEN=0 F  S APPTIEN=$O(^SC(CLINICIEN,"S",APPTDTTM,1,APPTIEN)) Q:'APPTIEN  D
 . . . Q:$P($G(^SC(CLINICIEN,"S",APPTDTTM,1,APPTIEN,0)),"^",9)="C"
 . . . Q:'$D(^SC(CLINICIEN,"S",APPTDTTM,1,APPTIEN,0))
 . . . S COUNT=COUNT+1,HASAPPTS=1
 . . . S ^XTMP("SDES949P-3",COUNT)="   ... and appointments are scheduled on: "_$$FMTE^XLFDT($P(APPTDTTM,"."),5)
 ;
 Q
