RGADDEDIT(RETURNJSON,SDCONTEXT,SDINPUT) ;;ADD/EDIT RESOURCE GROUP
 N RETURN,ELGFIELDSARRAY,ELGRETURN,RETN,ERRORS
 D VALCONTEXT^SDES2VALCONTEXT(.ERRORS,.SDCONTEXT)
 I $D(ERRORS) S ERRORS("Status")="",ERRORS("RSGroup",1)="" D BUILDJSON^SDES2JSON(.RETURNJSON,.ERRORS) Q
 I $G(SDCONTEXT("USER DUZ"))'="" N DUZ D DUZ^XUP(SDCONTEXT("USER DUZ"))
 S (RETURN,ELGFIELDSARRAY)=""
 D VALDINPUT(.ERRORS,.SDINPUT)
 I $D(ERRORS) S ERRORS("Status")="",ERRORS("RSGroup",1)="" D BUILDJSON^SDES2JSON(.RETURNJSON,.ERRORS) Q
 D RGMOD(.ELGFIELDSARRAY,.SDINPUT)
 I $D(ELGFIELDSARRAY("Error")) D BUILDJSON^SDES2JSON(.RETURNJSON,.ELGFIELDSARRAY) Q
 D FILEEASINFO(.ERRORS,$G(SDINPUT("RESOURCE GROUP IEN")),.SDCONTEXT)
 K RETN
 D BUILDGROUP^SDES2GETRESGROUP(.RETN,$G(SDINPUT("RESOURCE GROUP IEN")))
 M RETN=ELGFIELDSARRAY
 D BUILDJSON^SDES2JSON(.RETURNJSON,.RETN)
 Q
 ;
RGMOD(ELGARRAY,SDINPUT) ; Add or Edit Resource Group Name
 N SDRGIENS,SDRGFDA,SDRGMSG,SDRGM1,SDESRGIEN,SDESRGNAME
 S ELGARRAY("Status")=""
 S SDESRGIEN=$G(SDINPUT("RESOURCE GROUP IEN"))
 S SDESRGNAME=SDINPUT("RESOURCE GROUP NAME")
 S SDRGM1=""
 I +SDESRGIEN D
 . S SDRGIENS=SDESRGIEN_","
 . S SDRGFDA(409.832,SDRGIENS,.01)=SDESRGNAME ;NAME
 . D FILE^DIE("","SDRGFDA","SDRGMSG")
 . I $D(SDRGMSG) S ELGARRAY("Error")="Error in updating Resource Group. "_$G(SDRGMSG("DIERR",1,"TEXT",1)) Q
 . I '$D(SDRGMSG) S SDRGM1="Resource Group successfully updated."
 I '+SDESRGIEN D
 . S SDRGIENS="+1,"
 . K SDESRGIEN
 . S SDRGFDA(409.832,SDRGIENS,.01)=SDESRGNAME ;NAME
 . D UPDATE^DIE("","SDRGFDA","SDRGIENS","SDRGMSG")
 . I $D(SDRGMSG) S ELGARRAY("Error")="Error in adding Resource Group. "_$G(SDRGMSG("DIERR",1,"TEXT",1)) Q
 . S SDESRGIEN=+$G(SDRGIENS(1))
 . I '$D(SDRGMSG) S SDRGM1="Resource Group successfully added."
 . S SDESRGIEN=$O(^SDEC(409.832,"B",SDESRGNAME,0))
 . S SDINPUT("RESOURCE GROUP IEN")=SDESRGIEN
 S ELGARRAY("Status")=$G(SDRGM1)
 Q 
VALDINPUT(ERRORS,SDINPUT) ;Validate Input Array
 N SDDA,SDESRGIEN,SDESRGNAME
 S SDESRGIEN=$G(SDINPUT("RESOURCE GROUP IEN"))
 S SDESRGNAME=$G(SDINPUT("RESOURCE GROUP NAME"))
 ; Invalid Resource Group IEN
 I SDESRGIEN'="" I '$D(^SDEC(409.832,SDESRGIEN,0)) D ERRLOG^SDES2JSON(.ERRORS,276) Q
 ; Missing Resource Group Name
 I SDESRGNAME="" D ERRLOG^SDES2JSON(.ERRORS,275) Q
 ; Resource Group Name Length Invalid 
 I ($L($$TRIM^XLFSTR(SDESRGNAME))<3)!($L($$TRIM^XLFSTR(SDESRGNAME))>30) D ERRLOG^SDES2JSON(.ERRORS,310)
 I $D(^SDEC(409.832,"B",SDESRGNAME)) S SDESRGIEN=$O(^SDEC(409.832,"B",SDESRGNAME,0)) D
 . S SDINPUT("RESOURCE GROUP IEN")=SDESRGIEN
 Q 
FILEEASINFO(ERRORS,SDESRGIEN,SDCONTEXT) ; STORE EAS TRACKING INFO 
 K SDFDA,SDMSG
 S SDFDA(409.832,SDESRGIEN_",",100)=$G(SDCONTEXT("ACHERON AUDIT ID"))
 S SDFDA(409.832,SDESRGIEN_",",101)=$G(XWB(2,"RPC"))
 S SDFDA(409.832,SDESRGIEN_",",102)=$G(SDCONTEXT("APPID"))
 D FILE^DIE("","SDFDA","SDMSG")
 I $D(SDMSG) S ERRORS("Error")="Error in adding EAS INFO "_$G(SDMSG("DIERR",1,"TEXT",1))
 Q
